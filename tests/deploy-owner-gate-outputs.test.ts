import { expect, test } from "bun:test";
import { createHash } from "node:crypto";
import {
  existsSync,
  linkSync,
  lstatSync,
  mkdirSync,
  mkdtempSync,
  readdirSync,
  readFileSync,
  renameSync,
  rmSync,
  symlinkSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { DeployError } from "../scripts/deploy/errors.ts";
import { inspectMoneyNativeBuildSourceTree } from "../scripts/deploy/money-native-build-closure.ts";
import { runOwnerGateWithTransientOutputs } from "../scripts/deploy/owner-gate-outputs.ts";
import { createDeployProcess } from "../scripts/deploy/process.ts";

const outputs = [".wrangler", "dist", "console/dist", "site/dist"] as const;

async function fixture(
  action: (input: {
    base: string;
    owner: string;
    workspace: string;
    inspect: () => ReturnType<typeof inspectMoneyNativeBuildSourceTree>;
    gate: () => Promise<void>;
  }) => Promise<void>,
): Promise<void> {
  const base = mkdtempSync(join(tmpdir(), "owner-gate-outputs-test-"));
  const owner = join(base, "owner");
  const workspace = join(base, "workspace");
  mkdirSync(owner);
  mkdirSync(workspace);
  const sources = {
    "src/entry.ts": "export const source = 'reviewed';\n",
    "console/index.html": "reviewed console",
    "site/index.html": "reviewed site",
    "package.json": JSON.stringify({ scripts: { check: "bun gate.ts" } }),
    "gate.ts": `import {mkdirSync,writeFileSync} from "node:fs";
for(const path of ${JSON.stringify(outputs)}) {
  mkdirSync(path, {recursive:true}); writeFileSync(path+"/built", "generated output");
}`,
  };
  const expected = Object.entries(sources).map(([path, bytes]) => {
    mkdirSync(dirname(join(owner, path)), { recursive: true });
    writeFileSync(join(owner, path), bytes);
    return {
      path,
      executable: false,
      blob: createHash("sha1")
        .update(`blob ${Buffer.byteLength(bytes)}\0${bytes}`)
        .digest("hex"),
    };
  });
  const context = createDeployProcess({ repositoryRoot: owner });
  const gate = async () => {
    const result = await context.run([process.execPath, "run", "check"]);
    expect(result.exitCode).toBe(0);
  };
  try {
    await action({
      base,
      owner,
      workspace,
      inspect: () => inspectMoneyNativeBuildSourceTree(owner, expected),
      gate,
    });
  } finally {
    rmSync(base, { recursive: true, force: true });
  }
}

test("the same successful real gate needs its own outputs retained before native source closes", async () => {
  await fixture(async ({ owner, workspace, inspect, gate }) => {
    const before = inspect();
    await gate();
    expect(inspect).toThrow("differs from the reviewed complete Git tree");
    // Keep the RED control's generated bytes; the next invocation owns fresh paths.
    for (const name of outputs) {
      const retained = join(workspace, "red-control", name);
      mkdirSync(dirname(retained), { recursive: true });
      renameSync(join(owner, name), retained);
    }
    await runOwnerGateWithTransientOutputs(owner, workspace, gate);
    expect(inspect().contentDigest).toBe(before.contentDigest);
    const retained = readdirSync(workspace).filter((name) =>
      name.startsWith("owner-gate-outputs-"),
    );
    expect(retained).toHaveLength(1);
    for (const name of outputs) {
      expect(existsSync(join(owner, name))).toBe(false);
      expect(readFileSync(join(workspace, retained[0]!, name, "built"), "utf8")).toBe(
        "generated output",
      );
    }
  });
});

test("every pre-existing output is refused before the gate and its bytes stay untouched", async () => {
  await fixture(async ({ owner, workspace }) => {
    let calls = 0;
    for (const [index, name] of outputs.entries()) {
      mkdirSync(join(owner, name));
      writeFileSync(join(owner, name, "existing"), "someone else's data");
      await expect(
        runOwnerGateWithTransientOutputs(owner, workspace, async () => {
          calls++;
        }),
      ).rejects.toThrow("output already exists");
      expect(readFileSync(join(owner, name, "existing"), "utf8")).toBe("someone else's data");
      renameSync(join(owner, name), join(workspace, `existing-${index}`));
    }
    expect(calls).toBe(0);
    expect(readdirSync(workspace).some((name) => name.startsWith("owner-gate-outputs-"))).toBe(
      false,
    );
  });
});

test("a gate RED stays primary while its generated outputs are retained", async () => {
  await fixture(async ({ owner, workspace, inspect, gate }) => {
    const failure = new DeployError("preflight", "original gate RED", "original diagnostics");
    let caught: unknown;
    try {
      await runOwnerGateWithTransientOutputs(owner, workspace, async () => {
        await gate();
        throw failure;
      });
    } catch (error) {
      caught = error;
    }
    expect(caught).toBe(failure);
    expect(inspect().files).toBe(5);
    expect(readdirSync(workspace)).toHaveLength(1);
  });
});

test("a secondary retention refusal cannot replace the original gate RED", async () => {
  await fixture(async ({ owner, workspace }) => {
    const failure = new Error("original gate failure");
    let caught: unknown;
    try {
      await runOwnerGateWithTransientOutputs(owner, workspace, async () => {
        writeFileSync(join(owner, "dist"), "unexpected output file");
        throw failure;
      });
    } catch (error) {
      caught = error;
    }
    expect(caught).toBe(failure);
    expect(readFileSync(join(owner, "dist"), "utf8")).toBe("unexpected output file");
    expect(readdirSync(workspace)).toHaveLength(0);
  });
});

test("unlisted source bytes remain visible to the unchanged complete-tree guard", async () => {
  await fixture(async ({ owner, workspace, inspect }) => {
    await runOwnerGateWithTransientOutputs(owner, workspace, async () => {
      writeFileSync(join(owner, "unlisted.ts"), "unreviewed input");
    });
    expect(inspect).toThrow("differs from the reviewed complete Git tree");
    expect(readFileSync(join(owner, "unlisted.ts"), "utf8")).toBe("unreviewed input");
    expect(readdirSync(workspace)).toHaveLength(0);
  });
});

test("a gate-created output symlink is refused without moving its target or other outputs", async () => {
  await fixture(async ({ base, owner, workspace }) => {
    const foreign = join(base, "foreign");
    mkdirSync(foreign);
    writeFileSync(join(foreign, "keep"), "foreign bytes");
    await expect(
      runOwnerGateWithTransientOutputs(owner, workspace, async () => {
        mkdirSync(join(owner, ".wrangler"));
        writeFileSync(join(owner, ".wrangler", "own"), "own output");
        symlinkSync(foreign, join(owner, "dist"));
      }),
    ).rejects.toThrow("not an owned directory");
    expect(lstatSync(join(owner, "dist")).isSymbolicLink()).toBe(true);
    expect(readFileSync(join(foreign, "keep"), "utf8")).toBe("foreign bytes");
    expect(readFileSync(join(owner, ".wrangler", "own"), "utf8")).toBe("own output");
    expect(readdirSync(workspace)).toHaveLength(0);
  });
});

test("replacing a pinned source parent cannot move a foreign dist directory", async () => {
  await fixture(async ({ base, owner, workspace }) => {
    const foreign = join(base, "foreign");
    mkdirSync(join(foreign, "dist"), { recursive: true });
    writeFileSync(join(foreign, "dist", "keep"), "foreign bytes");
    await expect(
      runOwnerGateWithTransientOutputs(owner, workspace, async () => {
        renameSync(join(owner, "console"), join(base, "original-console"));
        symlinkSync(foreign, join(owner, "console"));
      }),
    ).rejects.toBeInstanceOf(DeployError);
    expect(readFileSync(join(foreign, "dist", "keep"), "utf8")).toBe("foreign bytes");
    expect(lstatSync(join(owner, "console")).isSymbolicLink()).toBe(true);
    expect(readdirSync(workspace)).toHaveLength(0);
  });
});

test("a workspace inside the source tree is refused before the gate", async () => {
  await fixture(async ({ owner }) => {
    const workspace = join(owner, "workspace");
    mkdirSync(workspace);
    let called = false;
    await expect(
      runOwnerGateWithTransientOutputs(owner, workspace, async () => {
        called = true;
      }),
    ).rejects.toThrow("outside its source tree");
    expect(called).toBe(false);
  });
});

test("replacing a pinned parent with another real directory still refuses retention", async () => {
  await fixture(async ({ base, owner, workspace }) => {
    const foreign = join(base, "foreign");
    mkdirSync(join(foreign, "dist"), { recursive: true });
    writeFileSync(join(foreign, "dist", "keep"), "foreign bytes");
    await expect(
      runOwnerGateWithTransientOutputs(owner, workspace, async () => {
        renameSync(join(owner, "console"), join(base, "original-console"));
        renameSync(foreign, join(owner, "console"));
      }),
    ).rejects.toThrow("parent directory changed");
    expect(readFileSync(join(owner, "console", "dist", "keep"), "utf8")).toBe("foreign bytes");
    expect(readdirSync(workspace)).toHaveLength(0);
  });
});

test("replacing the private workspace cannot receive the gate's outputs", async () => {
  await fixture(async ({ base, owner, workspace }) => {
    const foreign = join(base, "foreign-workspace");
    mkdirSync(foreign);
    writeFileSync(join(foreign, "keep"), "foreign bytes");
    await expect(
      runOwnerGateWithTransientOutputs(owner, workspace, async () => {
        mkdirSync(join(owner, "dist"));
        writeFileSync(join(owner, "dist", "own"), "own bytes");
        renameSync(workspace, join(base, "original-workspace"));
        renameSync(foreign, workspace);
      }),
    ).rejects.toThrow("parent directory changed");
    expect(readFileSync(join(workspace, "keep"), "utf8")).toBe("foreign bytes");
    expect(readFileSync(join(owner, "dist", "own"), "utf8")).toBe("own bytes");
    expect(readdirSync(workspace)).toEqual(["keep"]);
  });
});

test("nested symlinks never enter the workspace finalizer", async () => {
  await fixture(async ({ base, owner, workspace }) => {
    const foreign = join(base, "foreign-file");
    writeFileSync(foreign, "foreign bytes", { mode: 0o400 });
    await expect(
      runOwnerGateWithTransientOutputs(owner, workspace, async () => {
        mkdirSync(join(owner, "dist"));
        symlinkSync(foreign, join(owner, "dist", "borrowed"));
      }),
    ).rejects.toThrow("must be link-free");
    expect(readFileSync(foreign, "utf8")).toBe("foreign bytes");
    expect(lstatSync(foreign).mode & 0o777).toBe(0o400);
    expect(readdirSync(workspace)).toHaveLength(0);
  });
});

